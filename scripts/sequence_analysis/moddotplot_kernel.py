@dataclass(frozen=True)
class Settings:
    k: int = 21
    identity: float = 80.0
    sketch_size: int = 1000
    delta: float = 0.5
    ambiguous: bool = False

    def __post_init__(self):
        if not 1 <= self.k <= 65535 or not math.isfinite(self.identity) or not 0 <= self.identity <= 100:
            raise ValueError('Invalid k-mer size or identity threshold')
        if not 1 <= self.sketch_size <= 1_000_000 or not math.isfinite(self.delta) or not 0 <= self.delta <= 1:
            raise ValueError('Invalid sketch size or neighbor expansion')

    def sparsity(self, window):
        # Same rule as upstream MatrixConfig; fixed for a resolution, including
        # its shorter end windows, so a selection does not change the sketches.
        size = min(self.sketch_size, window)
        ratio = max(1, round(window / size))
        sparse = 2 ** (int(math.log2(ratio)) if ratio <= size else int(math.log2(max(1, ratio - 1))) + 1)
        return sparse, round(window / sparse)


class WindowSketch(NamedTuple):
    core: np.ndarray
    neighbors: np.ndarray
    interval: tuple[int, int]


class PreparedFasta:
    """Random access to HiCT's own single-record, 80-column UTF-8/ASCII export."""
    def __init__(self, path, length):
        self.stream = open(path, 'rb')
        self.length = int(length)
        header = self.stream.readline()
        if not header.startswith(b'>') or self.length < 0:
            self.stream.close()
            raise ValueError('Expected a prepared single-record FASTA')
        self.offset = self.stream.tell()
        first = self.stream.readline()
        if len(first.rstrip(b'\n')) != min(80, self.length):
            self.stream.close()
            raise ValueError('Prepared FASTA must use 80-column wrapping')

    def read(self, start, end):
        if not 0 <= start <= end <= self.length:
            raise ValueError('Sequence window outside frozen assembly')
        a, b = start + start // 80, end + end // 80
        self.stream.seek(self.offset + a)
        data = self.stream.read(b - a).replace(b'\n', b'')
        if len(data) != end - start:
            raise ValueError('Prepared FASTA is truncated or malformed')
        return data

    def close(self):
        self.stream.close()


def prepare_windows(read_sequence, sequence_length, windows, resolution, settings, log=lambda _: None, context_bounds=None):
    """Read/hash at most 8 MiB or 1024 windows per batch (plus one long window)."""
    windows = [tuple(map(int, w)) for w in windows]
    if resolution <= 0 or any(not 0 <= a < b <= sequence_length or b - a > resolution for a, b in windows):
        raise ValueError('Invalid source-bin sequence windows')
    sparse, expectation = settings.sparsity(resolution)
    flank = resolution * settings.delta
    if context_bounds is None:
        context_bounds = [(0, sequence_length)] * len(windows)
    if len(context_bounds) != len(windows) or any(not 0 <= lo <= a < b <= hi <= sequence_length
            for (a, b), (lo, hi) in zip(windows, context_bounds)):
        raise ValueError('Invalid scaffold context bounds')
    expanded = [(max(lo, round(a - flank)), min(hi, round(b + flank)))
                for (a, b), (lo, hi) in zip(windows, context_bounds)]
    order = sorted(range(len(windows)), key=lambda i: expanded[i])
    result = [None] * len(windows)
    cursor = 0
    while cursor < len(order):
        stop = cursor + 1
        start_bp, end_bp = expanded[order[cursor]]
        while stop < len(order) and stop - cursor < 1024:
            _, next_end = expanded[order[stop]]
            if max(end_bp, next_end) - start_bp > 8 * 1024 * 1024:
                break
            end_bp = max(end_bp, next_end)
            stop += 1
        sequence = read_sequence(start_bp, end_bp)
        if len(sequence) != end_bp - start_bp:
            raise ValueError('Sequence reader returned an incomplete interval')
        count = max(0, len(sequence) - settings.k + 1)
        indices = order[cursor:stop]
        bounds = []
        for collection in (windows, expanded):
            for i in indices:
                a, b = collection[i]
                left = min(count, a - start_bp)
                right = min(count, max(left, b - start_bp - settings.k + 1))
                bounds.append((left, right))
        packed = _nthash.sketch_kmers(sequence, settings.k, True, bounds, sparse,
                                     round(expectation / 2), settings.ambiguous)
        arrays = [np.frombuffer(x, dtype=np.uint64) for x in packed]
        for j, i in enumerate(indices):
            result[i] = WindowSketch(arrays[j], arrays[len(indices) + j], windows[i])
        cursor = stop
        log(f'Sketched {cursor}/{len(order)} source-bin windows at {resolution} bp')
    return result


def calculate_blocks(row_sketches, col_sketches, settings, accept, block_size=256, log=lambda _: None):
    if not 1 <= block_size <= 1024:
        raise ValueError('Identity block size must be between 1 and 1024')
    for start_r in range(0, len(row_sketches), block_size):
        r = row_sketches[start_r:start_r + block_size]
        for start_c in range(0, len(col_sketches), block_size):
            c = col_sketches[start_c:start_c + block_size]
            values = pairwiseContainmentMatrix([x[0] for x in c], [x[0] for x in r],
                [x[1] for x in c], [x[1] for x in r], settings.identity, settings.k, True)
            # Upstream selfContainmentMatrix pins genuine self windows to 100.
            # Adaptive core/neighbor sampling can otherwise lower that diagonal.
            # Empty evidence stays zero, including retained ambiguous windows.
            col_positions = {}
            for j, sketch in enumerate(c):
                col_positions.setdefault(sketch.interval, []).append(j)
            for i, sketch in enumerate(r):
                for j in col_positions.get(sketch.interval, ()):
                    values[i, j] = 100.0 if len(sketch.core) else 0.0
            accept(start_r, start_c, values)
        log(f'Compared {min(start_r + block_size, len(row_sketches))}/{len(row_sketches)} rows')
