"""Bounded HiCT adapter to the pinned, unmodified ModDotPlot identity kernel.

Windows are source-bin anchored in a frozen assembly, not regenerated by
summing finer cells. Full matrices are never allocated. Canonical ntHash makes
reverse-complement sequence windows comparable in either orientation.
"""
from __future__ import annotations
import math
from dataclasses import dataclass
from typing import NamedTuple
import numpy as np
from moddotplot import _nthash
from moddotplot.estimate_identity import pairwiseContainmentMatrix

